#!/usr/bin/env bash
# 由交叉编译产物生成 loongarch64 pacman 包（denial-flutter-engine / denial）
#
# 依赖: bsdtar, zstd
# 用法: ./contrib/loong64/package-pkg.sh [版本号]
set -euo pipefail

DENIAL_ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
WORK=${WORK:-$HOME/loong64-build/denial-main-build}
FLUTTER=${FLUTTER:-$WORK/checkout}
ENGINE_OUT=${ENGINE_OUT:-$FLUTTER/engine/src/flutter/out/denial_linux_loong64_release}
RUST_REL=${RUST_REL:-$WORK/rust/loongarch64-unknown-linux-gnu/release}
SHELL_OUT=${SHELL_OUT:-$WORK/shell-assembly}
APPS_OUT=${APPS_OUT:-$WORK/apps}
PKGVER=${1:-0.6.10}
PKGREL=1
ARCH=loongarch64
ABI=3.47.5.denial2
OUT=$WORK/pkgs
ARCHIVE=$DENIAL_ROOT/packaging/arch
META=$DENIAL_ROOT/prebuilt/flutter-engine/linux-x64-release

SIZE=0
BUILDDATE=$(date +%s)
log() { printf '\n=== %s ===\n' "$*"; }

finish_package() { # $1=root $2=pkgname $3=pkgver $4=pkgdesc $5=extra_pkginfo
  local root=$1 name=$2 ver=$3 desc=$4 extra=$5
  SIZE=$(du -sb --apparent-size "$root" | cut -f1)
  local ver_full=$3
  local ver_file=${ver_full#*:}
  {
    echo "# Generated by contrib/loong64/package-pkg.sh"
    echo "pkgname = $name"
    echo "pkgbase = $name"
    echo "pkgver = $ver_full-$PKGREL"
    echo "pkgdesc = $desc"
    echo "url = https://github.com/denialwm/denial"
    echo "builddate = $BUILDDATE"
    echo "packager = loong64 build <loong64@localhost>"
    echo "size = $SIZE"
    echo "arch = $ARCH"
    printf '%s\n' "$extra"
  } > "$root/.PKGINFO"
  local entries
  entries=$(find "$root" -mindepth 1 -maxdepth 1 ! -name .PKGINFO ! -name .MTREE -printf '%P\n')
  ( cd "$root" && bsdtar -czf .MTREE --format=mtree \
      --options='!all,use-set,type,uid,gid,mode,time,size,md5,sha256,link' \
      .PKGINFO $entries )
  local file=$OUT/$name-$ver_file-$PKGREL-$ARCH.pkg.tar.zst
  local tmp=$OUT/.pkg.tar
  ( cd "$root" && bsdtar -cf "$tmp" --format=pax .PKGINFO .MTREE $entries )
  zstd -q -19 -T0 -f "$tmp" -o "$file"
  rm -f "$tmp"
  echo "生成: $file"
}

stage_engine() {
  log "打包 denial-flutter-engine"
  local root=$WORK/pkg/denial-flutter-engine
  rm -rf "$root"; mkdir -p "$root"
  install -Dm755 "$ENGINE_OUT/libflutter_engine.so" \
    "$root/usr/lib/denial/flutter/lib/libflutter_engine.so"
  install -Dm644 "$ENGINE_OUT/icudtl.dat" \
    "$root/usr/lib/denial/flutter/data/icudtl.dat"

  local share=$root/usr/share/denial/flutter-engine
  local engine_rev flutter_rev
  engine_rev=$(cat "$FLUTTER/bin/internal/engine.version")
  flutter_rev=$(python3 -c 'import json,sys;print(json.load(open(sys.argv[1]))["flutter"]["revision"])' "$DENIAL_ROOT/prebuilt/flutter-engine/SOURCE_LOCK.json")
  install -Dm644 "$DENIAL_ROOT/prebuilt/flutter-engine/SOURCE_LOCK.json" "$share/SOURCE_LOCK.json"
  sha256sum "$ENGINE_OUT/libflutter_engine.so" | awk '{print $1}' > /tmp/engine.sha256
  install -Dm644 /tmp/engine.sha256 "$share/libflutter_engine.so.sha256"
  echo "$engine_rev" > "$share/ENGINE_REVISION"
  echo "$flutter_rev" > "$share/FLUTTER_REVISION"
  python3 - "$share" "$ARCHIVE/flutter-engine/manifest.json" "$engine_rev" <<'PY'
import json, sys, os
share, template, engine_rev = sys.argv[1], sys.argv[2], sys.argv[3]
manifest = json.load(open(template))
manifest["package"]["architecture"] = "loongarch64"
manifest["generation"] = "flutter-3.47.5-engine-" + engine_rev[:8] + "-denial-r1-loong64"
json.dump(manifest, open(os.path.join(share, "manifest.json"), "w"), indent=2)
PY
  sed -E 's#^(target_sysroot|custom_sysroot) = ".*"$#\1 = "@SYSROOT@"#' \
    "$ENGINE_OUT/args.gn" > "$share/args.gn"

  cat > /tmp/engine-build-info.md <<EOF
# Denial Flutter Engine (loongarch64)

- Flutter: 3.47.5 (denialwm/flutter \`$flutter_rev\`)
- Engine revision: \`$engine_rev\`
- ABI: \`$ABI\`
- 构建方式: 交叉编译（x86-64 host），见 \`contrib/loong64/build.sh\`
EOF
  install -Dm644 /tmp/engine-build-info.md "$root/usr/share/doc/denial-flutter-engine/BUILD_INFO.md"
  install -Dm644 "$META/LICENSE.flutter" "$root/usr/share/licenses/denial-flutter-engine/LICENSE.flutter"
  install -Dm644 "$META/LICENSE.third_party" "$root/usr/share/licenses/denial-flutter-engine/LICENSE.third_party"
  "$DENIAL_ROOT/tools/generate-denial-package-copyright" denial-flutter-engine \
    "$root/usr/share/doc/denial-flutter-engine/copyright" 2>/dev/null \
    || install -Dm644 "$DENIAL_ROOT/LICENSE" "$root/usr/share/doc/denial-flutter-engine/copyright"

  finish_package "$root" denial-flutter-engine "1:$ABI" \
    "Pinned source-built Flutter Engine runtime for Denial" \
    "license = BSD-3-Clause
provides = denial-flutter-engine-abi=$ABI
conflict = denial-flutter-engine-git
depend = fontconfig
depend = glibc
depend = gcc-libs"
}

stage_denial() {
  log "打包 denial"
  local root=$WORK/pkg/denial
  rm -rf "$root"; mkdir -p "$root"
  install -Dm755 "$RUST_REL/deniald"   "$root/usr/bin/deniald"
  install -Dm755 "$RUST_REL/denialctl" "$root/usr/bin/denialctl"
  install -Dm755 "$RUST_REL/denial-portal" "$root/usr/bin/denial-portal"
  install -Dm755 "$ARCHIVE/denial-session" "$root/usr/bin/denial-session"
  install -Dm755 "$DENIAL_ROOT/packaging/denial-suspend-mode" \
    "$root/usr/lib/systemd/system-sleep/denial-suspend-mode"
  install -Dm755 "$DENIAL_ROOT/packaging/denial-suspend-mode" \
    "$root/usr/lib/elogind/system-sleep/denial-suspend-mode"
  install -Dm644 "$DENIAL_ROOT/packaging/denial-session.target" \
    "$root/usr/lib/systemd/user/denial-session.target"
  install -Dm644 "$ARCHIVE/denial-portal.service" \
    "$root/usr/lib/systemd/user/denial-portal.service"

  install -dm755 "$root/usr/lib/denial/flutter/lib" "$root/usr/lib/denial/flutter/data"
  install -m755 "$SHELL_OUT/lib/libapp.so" "$root/usr/lib/denial/flutter/lib/libapp.so"
  cp -a "$SHELL_OUT/flutter_assets" "$root/usr/lib/denial/flutter/data/flutter_assets"
  chmod -R u=rwX,go=rX "$root/usr/lib/denial/flutter/data/flutter_assets"

  # 独立应用（denial-app runner、polkit、插件管理器）与预编译插件 bundle
  if [ -x "$RUST_REL/denial-app" ]; then
    install -Dm755 "$RUST_REL/denial-app" "$root/usr/bin/denial-app"
    [ -x "$RUST_REL/denial-polkit-agent" ] && \
      install -Dm755 "$RUST_REL/denial-polkit-agent" "$root/usr/bin/denial-polkit-agent"
    if [ -d "$APPS_OUT/polkit" ]; then
      cp -a "$APPS_OUT/polkit" "$root/usr/lib/denial/polkit"
      chmod -R u=rwX,go=rX "$root/usr/lib/denial/polkit"
    fi
    if [ -d "$APPS_OUT/plugin-manager" ]; then
      cp -a "$APPS_OUT/plugin-manager" "$root/usr/lib/denial/plugin-manager"
      chmod -R u=rwX,go=rX "$root/usr/lib/denial/plugin-manager"
      ln -s ../lib/denial/plugin-manager/denial-plugin-manager \
        "$root/usr/bin/denial-plugin-manager"
    fi
  fi

  install -Dm644 "$ARCHIVE/denial.desktop" "$root/usr/share/wayland-sessions/denial.desktop"
  install -Dm644 "$ARCHIVE/denial-portals.conf" "$root/usr/share/xdg-desktop-portal/denial-portals.conf"
  install -Dm644 "$ARCHIVE/denial.portal" "$root/usr/share/xdg-desktop-portal/portals/denial.portal"
  install -Dm644 "$ARCHIVE/org.freedesktop.impl.portal.desktop.denial.service" \
    "$root/usr/share/dbus-1/services/org.freedesktop.impl.portal.desktop.denial.service"
  install -Dm644 "$ARCHIVE/xdg-desktop-portal-wlr-Denial" \
    "$root/etc/xdg/xdg-desktop-portal-wlr/Denial"
  install -Dm644 "$ARCHIVE/outputs.conf" "$root/etc/denial/outputs.conf"
  install -Dm644 "$ARCHIVE/session.conf" "$root/etc/denial/session.conf"
  install -Dm644 "$DENIAL_ROOT/packaging/geoclue-denial.conf" "$root/etc/geoclue/conf.d/90-denial.conf"
  install -Dm644 "$DENIAL_ROOT/packaging/denial-fingerprint.rules" \
    "$root/usr/share/polkit-1/rules.d/50-denial-fingerprint.rules"

  install -Dm644 "$DENIAL_ROOT/README.md" "$root/usr/share/doc/denial/README.md"
  install -Dm644 "$DENIAL_ROOT/packages/denial_flutter_sdk/assets/wallpapers/ATTRIBUTION.md" \
    "$root/usr/share/doc/denial/WALLPAPERS.md"
  install -Dm644 "$DENIAL_ROOT/packages/denial_flutter_sdk/assets/cursors/BIBATA_MODERN_ICE.md" \
    "$root/usr/share/doc/denial/CURSORS.md"
  "$DENIAL_ROOT/tools/generate-denial-package-copyright" denial \
    "$root/usr/share/doc/denial/copyright" 2>/dev/null \
    || install -Dm644 "$DENIAL_ROOT/LICENSE" "$root/usr/share/doc/denial/copyright"
  for m in denialctl deniald denial-session denial-portal; do
    install -Dm644 "$DENIAL_ROOT/docs/man/$m.1" "$root/usr/share/man/man1/$m.1"
  done
  mkdir -p "$root/usr/share/denial"
  echo "$PKGVER" > "$root/usr/share/denial/version"

  finish_package "$root" denial "$PKGVER" \
    "Flutter-native Wayland compositor and desktop shell" \
    "license = GPL-3.0-or-later
license = Apache-2.0
license = CC-BY-SA-4.0
license = GPL-3.0-only
license = OFL-1.1
depend = adobe-source-han-sans-cn-fonts
depend = bash
depend = coreutils
depend = ddcutil
depend = denial-flutter-engine
depend = denial-flutter-engine-abi=$ABI
depend = dbus
depend = fontconfig
depend = glibc
depend = git
depend = libgcc
depend = libglvnd
depend = libinput
depend = libpulse
depend = libxkbcommon
depend = mesa
depend = pam
depend = polkit
depend = wayland
depend = rtkit
depend = seatd
depend = systemd-libs
depend = vulkan-driver
depend = vulkan-icd-loader
depend = xkeyboard-config
depend = xdg-desktop-portal
depend = xdg-desktop-portal-gtk
depend = xdg-desktop-portal-wlr
depend = xorg-xwayland
depend = zenity
optdepend = fprintd: fingerprint unlock and enrollment
optdepend = networkmanager: Wi-Fi and network controls through NetworkManager
optdepend = pipewire-pulse: desktop audio controls
optdepend = power-profiles-daemon: system power profiles
optdepend = sddm: graphical login and session selection
optdepend = upower: battery and power status
conflict = denial-git
conflict = denial-app-settings
replaces = denial-app-settings
backup = etc/denial/outputs.conf
backup = etc/denial/session.conf
backup = etc/xdg/xdg-desktop-portal-wlr/Denial"
}

mkdir -p "$OUT" "$WORK/pkg"
stage_engine
stage_denial
log "完成"
ls -lh "$OUT"
